import assert from 'node:assert/strict';
import {deadlineTime,deadlineState,deadlineNotifications,dateAfterDays,seoulDate,participationStep,bugValidation,migrateFeatures} from './src/playtest-features.js';
import {validateMedia,IMAGE_LIMIT,VIDEO_LIMIT} from './src/media-store.js';
const due=deadlineTime('2026-11-16');
assert.equal(due,Date.parse('2026-11-16T14:59:59.999Z'));
assert.ok(Number.isNaN(deadlineTime('2026-02-30')));
assert.equal(deadlineState('',due),'none');
assert.equal(deadlineState('2026-11-16',due),'soon');
assert.equal(deadlineState('2026-11-16',due+1),'overdue');
assert.equal(deadlineState('2026-11-16',due-48*3600000),'soon');
assert.equal(deadlineState('2026-11-16',due-48*3600000-1),'open');
assert.equal(seoulDate(new Date('2026-11-16T16:00:00Z')),'2026-11-17');
assert.equal(dateAfterDays(1,new Date('2026-12-31T01:00:00Z')),'2027-01-01');
const state=migrateFeatures({tests:[{id:'a',deadline:'2026-11-16',status:'open'}],mine:{a:{status:'applied'}}});
assert.equal(deadlineNotifications(state,due).length,1);
assert.equal(deadlineNotifications(state,due)[0].id,deadlineNotifications(state,due-1)[0].id);
state.mine.a.status='done';assert.equal(deadlineNotifications(state,due).length,0);
state.mine.a.status='waiting';assert.equal(deadlineNotifications(state,due).length,0);
state.mine.a.status='applied';state.tests[0].status='hidden';assert.equal(deadlineNotifications(state,due).length,0);
assert.equal(participationStep({status:'waiting'}),1);
assert.equal(participationStep({status:'applied'}),2);
assert.equal(participationStep({status:'applied',startedAt:'date'}),3);
assert.equal(participationStep({status:'done'}),4);
const image={type:'image/png',size:IMAGE_LIMIT},video={type:'video/mp4',size:VIDEO_LIMIT};
assert.equal(validateMedia([], [image,video]),'');
assert.notEqual(validateMedia([], [{...image,size:IMAGE_LIMIT+1}]),'');
assert.notEqual(validateMedia([], [{...video,size:VIDEO_LIMIT+1}]),'');
assert.notEqual(validateMedia([], [{type:'image/svg+xml',size:100}]),'');
assert.notEqual(validateMedia(Array.from({length:6},()=>({kind:'image'})),[image]),'');
assert.notEqual(validateMedia([],[video],{imagesOnly:true,maxImages:1,maxVideos:0}),'');
assert.notEqual(validateMedia([{kind:'video'}],[video]),'');
assert.notEqual(validateMedia([], [{...image,size:0}]),'');
const bug={title:'Crash',description:'The game crashes on the title screen.',steps:'Start the game then press play.',device:'Windows 11',severity:'critical'};
assert.equal(bugValidation(bug),'');
assert.notEqual(bugValidation({...bug,steps:''}),'');
assert.notEqual(bugValidation({...bug,severity:'invalid'}),'');
console.log('PASS deadline boundaries and time zone, reminder eligibility, progress, upload limits and bug validation');

const {validateFeedbackIssue,isLegacyBugQuestion}=await import('./src/playtest-features.js');
const reports=[{id:'b1',testId:'t1',testerId:'me'},{id:'b2',testId:'t2',testerId:'me'},{id:'b3',testId:'t1',testerId:'other'}];
assert.equal(validateFeedbackIssue('none',[],reports,'t1'),'');
assert.equal(validateFeedbackIssue('reported',['b1'],reports,'t1'),'');
for(const ids of [[],['missing'],['b2'],['b3']])assert.notEqual(validateFeedbackIssue('reported',ids,reports,'t1'),'');
assert.notEqual(validateFeedbackIssue('new',[],reports,'t1'),'');
assert.notEqual(validateFeedbackIssue('',[],reports,'t1'),'');
assert.equal(isLegacyBugQuestion({type:'text',required:false,label:'발견한 버그가 있다면 적어 주세요.'}),true);
assert.equal(isLegacyBugQuestion({type:'text',required:true,label:'발견한 버그가 있다면 적어 주세요.'}),false);
assert.equal(isLegacyBugQuestion({type:'text',required:false,label:'커스텀 질문'}),false);
console.log('PASS issue linking ownership, wrong-test prevention, new-report gate and legacy question preservation');
